const regionNamesCache = {};

/** Localize an ISO-3166 alpha-2 country code using Intl.DisplayNames when supported. */
export function locCountry(code, fallbackName, lang) {
    if (!code) return fallbackName || "";
    const upper = String(code).toUpperCase();
    if (lang === "en" && fallbackName && fallbackName.toUpperCase() !== upper) return fallbackName;
    try {
        if (!regionNamesCache[lang]) {
            regionNamesCache[lang] = new Intl.DisplayNames([lang || "en"], { type: "region" });
        }
        return regionNamesCache[lang].of(upper) || fallbackName || upper;
    } catch (_) {
        return fallbackName || upper;
    }
}

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";

/** Replace Latin digits with Persian ones (used whenever lang === "fa"). */
export function toFaDigits(str) {
    return String(str).replace(/[0-9]/g, (d) => FA_DIGITS[+d]);
}

/** Localize a number/string per language. */
export function locNum(value, lang) {
    return lang === "fa" ? toFaDigits(value) : String(value);
}

/** Percent with the proper localized sign (٪ for Persian), BiDi-isolated so RTL never flips `۷۵٪` to `٪۷۵`. */
export function locPct(value, lang) {
    const out = locNum(value, lang) + (lang === "fa" ? "٪" : "%");
    return lang === "fa" ? `\u2066${out}\u2069` : out;
}

/** Localized singular/plural day unit (proper EN & RU declension). */
export function fmtDaysUnit(n, lang) {
    const v = Math.abs(Math.round(Number(n) || 0));
    if (lang === "ru") return pickRuPlural(v, ["день", "дня", "дней"]);
    if (lang === "fa") return "روز";
    if (lang === "zh") return "天";
    return v === 1 ? "day" : "days";
}

